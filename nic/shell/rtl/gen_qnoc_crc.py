#!/usr/bin/env python3
"""Generate qnoc_crc512.v: the XOR networks of the C2H packet CRC.

The CPM samples s_axis_c2h_tcrc on tlast: CRC-32 (poly 0x04C11DB7, not
reflected, no final XOR) over the whole packet, seeded with all ones at the
first beat. Each beat feeds all 512 bits MSB first (bit 511 first); on the
last beat the empty bytes (mty, at the top) are zero.

The update is linear: crc' = A*crc ^ B*data. This script derives A and B from
the serial definition and writes them as explicit XOR masks:
  qnoc_crc512_dpart  data -> 32 x 8 partial parities (64 data bits each)
  qnoc_crc512_amul   crc  -> A*crc, plus SOP = A*ones (the seed term)
    python3 gen_qnoc_crc.py > qnoc_crc512.v
"""
POLY = 0x04C11DB7
W = 512


def step(crc, data):
    for i in range(W):
        bit = (data >> (W - 1 - i)) & 1
        fb = ((crc >> 31) & 1) ^ bit
        crc = ((crc << 1) & 0xFFFFFFFF) ^ (POLY if fb else 0)
    return crc


def main():
    bcol = [step(0, 1 << d) for d in range(W)]       # B * e_d
    acol = [step(1 << c, 0) for c in range(32)]      # A * e_c
    sop = step(0xFFFFFFFF, 0)
    # self-check of linearity on one random-looking vector
    import random
    r = random.Random(1)
    for _ in range(4):
        d = r.getrandbits(W)
        c = r.getrandbits(32)
        lin = 0
        for i in range(W):
            if (d >> i) & 1:
                lin ^= bcol[i]
        for i in range(32):
            if (c >> i) & 1:
                lin ^= acol[i]
        assert lin == step(c, d)
    out = []
    out.append("// Generated by gen_qnoc_crc.py, do not edit.")
    out.append("// C2H packet CRC-32 (0x04C11DB7, MSB first, 512-bit beats): crc' = A*crc ^ B*data")
    out.append("`timescale 1ns / 1ps")
    out.append("")
    out.append("// p[8*j+k] = parity of data[64k+63:64k] over the B mask of crc bit j")
    out.append("module qnoc_crc512_dpart (input wire [511:0] d, output wire [255:0] p);")
    for j in range(32):
        mask = 0
        for i in range(W):
            if (bcol[i] >> j) & 1:
                mask |= 1 << i
        for k in range(8):
            m = (mask >> (64 * k)) & ((1 << 64) - 1)
            out.append(f"    assign p[{8 * j + k}] = ^(d[{64 * k + 63}:{64 * k}] & 64'h{m:016x});")
    out.append("endmodule")
    out.append("")
    out.append("// a = A*c; sop = A*32'hFFFFFFFF (the all-ones seed pushed through one beat)")
    out.append("module qnoc_crc512_amul (input wire [31:0] c, output wire [31:0] a, output wire [31:0] sop);")
    for j in range(32):
        mask = 0
        for i in range(32):
            if (acol[i] >> j) & 1:
                mask |= 1 << i
        out.append(f"    assign a[{j}] = ^(c & 32'h{mask:08x});")
    out.append(f"    assign sop = 32'h{sop:08x};")
    out.append("endmodule")
    print("\n".join(out))


if __name__ == "__main__":
    main()
